#!/usr/bin/env python3
"""evals/patala/tasks/argmap_eval.py — PĀṬALA-ARGMAP-NAT (Inspect AI task, devpath1 E2-01).

The ARGMAP NAT harness: evaluates REAL, committed argument maps (Agent 2's `argument_map_worker`
output) against the ARGMAP contract, using the SAME cross-lane EvaluationCandidate/EvaluationFinding
objects as the T1 eval (no ARGMAP-specific handoff format).

Design (EVAL-CONTRACT):
  - CLAIM CLASS: NAT (naturally occurring, committed ARGMAP objects; gold = independently
    adjudicated, never generated by the verifier).
  - SYSTEM UNDER TEST: a deterministic structural/evaluative verifier of an ARGMAP (shape +
    natural-failure families). This is an AGENT-1 verifier (critic), not the generator.
  - INDEPENDENT GOLD: expected verdicts come from committed-ARGMAP semantics + the contract
    (a faithful map is NODE/ROLE/EDGE/SPEAKER/SCOPE/OPEN/INFERENCE clean), never from the verifier.
  - FROZEN SOLVER INPUT: the solver consumes the FROZEN candidate object only.
  - SPLITS: the one committed map (kramasadbhava:v1) is dev/known; held-out comes as the corpus grows.
  - METRICS: verdict accuracy, shape pass rate, per-dimension recall, mutation sensitivity.
  - BOUNDARY: passing = engineering validity of a verifier over the CURRENT committed maps. It is
    NOT_HUMAN_REVIEWED and does NOT establish generator accuracy or gate Agent 2.

This task currently ships the harness + contract, seeded with the single committed real map. It is
the "waiting-time" work (handover): ready to consume the moment Agent 2 emits a real ARGMAP batch.

Run (deterministic, no model calls):
  cd /root/projects/patala
  machinelearning/research/.venv/bin/python -m inspect_ai eval \
      source-evidence/evals/patala/tasks/argmap_eval.py --model mockllm/mockllm
"""
from __future__ import annotations

import hashlib
import json
import os
import sys

from inspect_ai import Task, task
from inspect_ai.dataset import MemoryDataset, Sample
from inspect_ai.scorer import Score, metric, scorer
from inspect_ai.scorer._metric import SampleScore
from inspect_ai.solver import Solver, solver

# cross-lane contract (shared with T1) + the ARGMAP contract
_TASKS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, _TASKS)
from evaluation_candidate import EvaluationCandidate          # noqa: E402
from evaluation_finding import EvaluationFinding              # noqa: E402
import argmap_contract as C                                    # noqa: E402

BENCH = "PĀṬALA-ARGMAP-NAT"
VERSION = "v0.1"
ROOT = os.path.abspath(os.path.join(_TASKS, "..", "..", "..", ".."))
REGISTRY_DIR = os.path.join(ROOT, "data", "corpus", "registries")
PINNED_INSPECT = "inspect-ai==0.3.258"


def sha256(obj) -> str:
    return hashlib.sha256(json.dumps(obj, sort_keys=True).encode("utf-8")).hexdigest()


def _sut_source() -> str:
    import inspect as _inspect
    return _inspect.getsource(verify_argmap) + _inspect.getsource(C.check_shape)


def _load_candidates() -> list[EvaluationCandidate]:
    """Load every committed ARGMAP from the registry as a frozen candidate."""
    p = os.path.join(REGISTRY_DIR, "argmap-registry.jsonl")
    cands = []
    if os.path.exists(p):
        for line in open(p, encoding="utf-8"):
            line = line.strip()
            if line:
                cands.append(EvaluationCandidate.from_registry_row(json.loads(line)))
    return cands


# ── the SUT: a bounded structural/evaluative verifier of an ARGMAP ────────────
def verify_argmap(candidate: EvaluationCandidate) -> dict:
    """Verify one ARGMAP candidate against the contract.

    Returns {ok, verdict, dimensions, findings, problems}. Dimensions are the 8 contract dims,
    each CLEAN|OPEN|DEFECT. The verifier NOMINATES defects (structural/engineering), never settles
    truth — a clean map is engineering-valid, not scholar-correct.
    """
    am = (candidate.payload or {}).get("argument_map", {})
    missing = C.check_shape(am)
    problems = []
    dimensions = {d: "CLEAN" for d in C.DIMENSIONS}
    # SHAPE: all four canonical sections must be present
    if missing:
        dimensions["NODE"] = "DEFECT"
        problems.append(f"missing canonical section(s): {missing}")
    # SCOPE: an open item rendered as a resolved decision is scope/boundary inflation
    open_items = am.get("open_items", [])
    if open_items and not isinstance(open_items, list):
        dimensions["OPEN"] = "DEFECT"
        problems.append("open_items is not a well-formed list")
    else:
        # every open_item must carry an explicit OPEN/NEEDS_REVIEW status (never silently resolved)
        for oi in open_items:
            st = str(oi.get("status", "")).upper() if isinstance(oi, dict) else ""
            if st not in ("OPEN", "NEEDS_REVIEW"):
                dimensions["OPEN"] = "DEFECT"
                problems.append(f"open_item not flagged OPEN/NEEDS_REVIEW: {str(oi)[:60]}")
    # INFERENCE: an argument step that asserts an inference with no grounding cue
    steps = am.get("argument_steps", [])
    if isinstance(steps, list):
        for i, s in enumerate(steps):
            low = str(s).lower()
            if any(cue in low for cue in C._INFERENCE_CUES):
                if not any(cue in low for cue in C._GROUNDING_CUES):
                    dimensions["INFERENCE"] = "DEFECT"
                    problems.append(f"unsupported inference at step {i}: {str(s)[:60]}")
    # SUPPORT: decision_for_l2 must reference the passage / not be a universal overreach
    decision = str(am.get("decision_for_l2", ""))
    if decision and any(u in decision.lower() for u in C._UNIVERSAL_CUES):
        dimensions["SCOPE"] = "DEFECT"
        problems.append("decision_for_l2 contains universal overreach (scope inflation candidate)")
    ok = (len(problems) == 0)
    return {
        "ok": ok,
        "verdict": "PASS" if ok else "FAIL",
        "dimensions": dimensions,
        "problems": problems,
    }


# ── dataset ───────────────────────────────────────────────────────────────────
def build_dataset() -> MemoryDataset:
    cands = _load_candidates()
    samples = []
    for cand in cands:
        cand_dict = cand.emit()
        samples.append(Sample(
            id=cand.candidate_id,
            input=json.dumps(cand_dict, ensure_ascii=False),   # FROZEN candidate object only
            metadata={
                "bench": BENCH, "version": VERSION,
                "object_ref": cand.object_ref, "version": cand.version,
                "candidate_hash": cand_dict["candidate_hash"],
                "pinned_inspect": PINNED_INSPECT,
            },
        ))
    return MemoryDataset(samples)


# ── solver: consumes only the frozen candidate ────────────────────────────────
@solver
def run_verifier() -> Solver:
    async def solve(state, generate):
        cand = EvaluationCandidate.from_dict(json.loads(state.input))
        res = verify_argmap(cand)
        state.output.completion = res["verdict"]
        state.store.set("dimensions", res["dimensions"])
        state.store.set("problems", res["problems"])
        return state
    return solve


# ── metrics ───────────────────────────────────────────────────────────────────
@metric
def shape_pass_rate():
    def compute(scores: list[SampleScore]):
        vals = [s.score.as_float() for s in scores]
        return sum(vals) / len(vals) if vals else float("nan")
    return compute


@metric
def mutation_sensitivity():
    """Fraction of samples where a defect is correctly caught (verifier competence)."""
    def compute(scores: list[SampleScore]):
        mut = [s for s in scores if s.sample_metadata and s.sample_metadata.get("expected_defect")]
        if not mut:
            return float("nan")
        return sum(1 for s in mut if s.score.as_float() == 1.0) / len(mut)
    return compute


# ── scorer ────────────────────────────────────────────────────────────────────
@scorer(metrics=[shape_pass_rate(), mutation_sensitivity()])
def contract_score():
    async def score(state, target):
        res_verdict = state.output.completion
        dims = state.store.get("dimensions", {})
        problems = state.store.get("problems", [])
        clean = (len(problems) == 0)
        return Score(
            value=clean,
            answer=res_verdict,
            explanation=(f"object={state.metadata.get('version')} verdict={res_verdict} "
                         f"dimensions={dims} problems={problems}"),
        )
    return score


@task
def argmap_nat():
    ds = build_dataset()
    return Task(
        dataset=ds,
        solver=run_verifier(),
        scorer=[contract_score()],
        name="argmap_nat",
        version=VERSION,
        metadata={"bench": BENCH, "pinned_inspect": PINNED_INSPECT,
                  "dataset_hash": sha256([{"id": s.id, "input": s.input}
                                          for s in ds.samples]),
                  "sut_hash": sha256(_sut_source()),
                  "n_candidates": len(ds.samples)},
    )


if __name__ == "__main__":
    ds = build_dataset()
    print(f"{BENCH} {VERSION}: {len(ds.samples)} committed ARGMAP candidate(s)")
    for s in ds.samples:
        cand = EvaluationCandidate.from_dict(json.loads(s.input))
        res = verify_argmap(cand)
        print(f"  {res['verdict']:4} {cand.version:44} hash={s.metadata['candidate_hash'][:10]}")
        for p in res["problems"]:
            print(f"         - {p}")
